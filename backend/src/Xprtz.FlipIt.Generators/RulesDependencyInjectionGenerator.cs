using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Immutable;
using System.Text;

namespace Xprtz.FlipIt.Generators;

[Generator]
public class RulesDependencyInjectionGenerator : IIncrementalGenerator
{
    private const string BaseInterfaceName = "IRule";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var providers = context.SyntaxProvider.CreateSyntaxProvider(
            predicate:
            static (node, _) => node is ClassDeclarationSyntax
            {
                BaseList: not null
            },
            transform: static (ctx, _) =>
            {
                var symbol = ctx.SemanticModel.GetDeclaredSymbol(ctx.Node) as INamedTypeSymbol;

                var implementedInterfaces = symbol!.AllInterfaces;
                if (!implementedInterfaces.Any(x => x.Name == BaseInterfaceName))
                {
                    return null;
                }

                var targetInterface = implementedInterfaces.First(x => x.Name != BaseInterfaceName);

                return new RuleInjectionModel { Name = symbol.ToString(), InterfaceName = targetInterface.ToString() };
            });

        var collect = providers.Where(x => x is not null).Collect();

        context.RegisterSourceOutput(collect, Emit!);
    }

    private void Emit(SourceProductionContext context, ImmutableArray<RuleInjectionModel> models)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine();

        sb.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine();

        sb.AppendLine("public static class RulesDependencyInjection");
        sb.AppendLine("{");
        sb.AppendLine("    public static void AddRules(this IServiceCollection services)");
        sb.AppendLine("    {");

        foreach (var model in models)
        {
            sb.AppendLine($"        services.AddScoped<{model.InterfaceName}, {model.Name}>();");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource("RulesDependencyInjection.g.cs", sb.ToString());
    }

    private class RuleInjectionModel
    {
        public string Name { get; set; } = string.Empty;
        public string InterfaceName { get; set; } = string.Empty;
    }
}
